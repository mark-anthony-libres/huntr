/// Whether [emoji] is found by [query]: each of its words must start one
/// of the emoji's words (or the name of its kind, e.g. hearts).
bool emojiMatches(String emoji, String query, {String kind = ''}) {
  final words = '${emojiWords[emoji] ?? ''} ${kind.toLowerCase()}'
      .split(' ')
      .where((w) => w.isNotEmpty);
  return query
      .toLowerCase()
      .split(RegExp(r'\s+'))
      .where((q) => q.isNotEmpty)
      .every((q) => words.any((w) => w.startsWith(q)));
}
